def estimate_build_cost(
    resources: list[dict[str, Any]], region: str | None = None
) -> ScanResult:
    """Estimate monthly AWS costs and generate a Terraform scaffold.

    Args:
        resources: List of dicts with ``type``, ``count``, and optionally
            ``instance_type`` or ``instance_class``.
        region: Unused -- Pricing API is always queried in ``us-east-1``.

    Returns:
        ScanResult with ``data`` as a :class:`CostEstimate` dict.
    """
    try:
        pricing = get_client("pricing", "us-east-1")
    except (ClientError, BotoCoreError) as e:
        return error_result(
            data={},
            errors=[
                scan_error_from_exception(
                    service="pricing",
                    operation="CreateClient",
                    exc=e,
                )
            ],
        )

    estimates: list[ResourceEstimate] = []

    for spec in resources:
        rtype = str(spec.get("type", "")).lower()
        count = int(spec.get("count", 1))
        if rtype not in _SUPPORTED_TYPES:
            continue

        unit_monthly_cost: float | None = None
        label: str = ""
        pricing_note: str = ""

        if rtype == "ec2":
            instance_type = str(spec.get("instance_type", "t3.micro"))
            hourly = _get_ec2_price(pricing, instance_type)
            if hourly is not None:
                unit_monthly_cost = round(hourly * _HOURS_PER_MONTH, 2)
            label = f"{instance_type} x{count}"
            pricing_note = "on-demand Linux" if hourly else "price unavailable"

        elif rtype == "rds":
            instance_class = str(
                spec.get("instance_class", spec.get("db_instance_class", "db.t3.micro"))
            )
            hourly = _get_rds_price(pricing, instance_class)
            if hourly is not None:
                unit_monthly_cost = round(hourly * _HOURS_PER_MONTH, 2)
            label = f"{instance_class} x{count}"
            pricing_note = (
                "on-demand MySQL Single-AZ" if hourly else "price unavailable"
            )

        elif rtype == "lambda":
            unit_monthly_cost = 5.0
            label = f"Lambda x{count}"
            pricing_note = "estimated (pay-per-use; actual varies)"

        elif rtype == "nat_gateway":
            unit_monthly_cost = 35.0
            label = f"NAT Gateway x{count}"
            pricing_note = "hourly charge only; data transfer extra"

        elif rtype == "load_balancer":
            unit_monthly_cost = 22.50
            label = f"ALB x{count}"
            pricing_note = "base hourly; LCU charges extra"

        elif rtype == "s3":
            unit_monthly_cost = None
            label = f"S3 bucket x{count}"
            pricing_note = "bucket cost: $0.023/GB/month (size unknown)"

        total_monthly_cost = (
            round(unit_monthly_cost * count, 2)
            if unit_monthly_cost is not None
            else None
        )

        estimates.append(
            {
                "resource_type": rtype,
                "label": label,
                "count": count,
                "unit_monthly_cost": unit_monthly_cost,
                "total_monthly_cost": total_monthly_cost,
                "pricing_note": pricing_note,
            }
        )

    # Totals (only where cost is known)
    known_costs = [
        e["total_monthly_cost"]
        for e in estimates
        if e["total_monthly_cost"] is not None
    ]
    total_monthly = sum(known_costs) if known_costs else None
    total_annual = round(total_monthly * 12, 2) if total_monthly is not None else None

    scaffold = _generate_terraform(resources)

    result: CostEstimate = {
        "resources": estimates,
        "total_monthly_cost": (
            round(total_monthly, 2) if total_monthly is not None else None
        ),
        "total_annual_cost": total_annual,
        "terraform_scaffold": scaffold,
        "currency": "USD",
    }
    return ok_result(result)
